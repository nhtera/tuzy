#!/usr/bin/env node
/**
 * Generates wrangler.dev.gen.jsonc (gitignored) from wrangler.jsonc for local `wrangler dev`.
 *
 * Why (GATE B): when `routes` are configured, `wrangler dev` rewrites both the request URL and
 * the `Host` header to the first route's zone ("tuzy.dev"), which destroys Host-based tunnel
 * routing. Dropping `routes` keeps the real Host (e.g. "shop.localhost:8787").
 *
 * wrangler.jsonc stays the single source of truth; the dev copy only:
 *   - removes `routes`
 *   - forces `vars.BASE_DOMAIN = "localhost"` so `<name>.localhost` resolves as a tunnel host
 * It is written next to wrangler.jsonc so relative paths (main, migrations, .dev.vars) resolve the same.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { applyEdits, modify, parse } from "jsonc-parser";

const edgeDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcPath = join(edgeDir, "wrangler.jsonc");
const outPath = join(edgeDir, "wrangler.dev.gen.jsonc");

const DEV_BASE_DOMAIN = "localhost";
const format = { formattingOptions: { insertSpaces: true, tabSize: 2 } };

let text = readFileSync(srcPath, "utf8");
const errors = [];
parse(text, errors, { allowTrailingComma: true });
if (errors.length > 0) {
  console.error(`gen-dev-config: ${srcPath} is not valid JSONC (${errors.length} parse errors)`);
  process.exit(1);
}

text = applyEdits(text, modify(text, ["routes"], undefined, format));
text = applyEdits(text, modify(text, ["vars", "BASE_DOMAIN"], DEV_BASE_DOMAIN, format));

const header = "// GENERATED by scripts/gen-dev-config.mjs from wrangler.jsonc: do not edit, not committed.\n";
writeFileSync(outPath, header + text);
console.log(`gen-dev-config: wrote ${outPath} (routes removed, BASE_DOMAIN=${DEV_BASE_DOMAIN})`);
